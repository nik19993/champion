// Usage: node scripts/verify-training-register-ui.mjs ESBUILD_MODULE PLAYWRIGHT_MODULE CHROMIUM_PATH
import assert from "node:assert/strict";
import { readFile, mkdtemp, rm } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { pathToFileURL, fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { build } = await import(pathToFileURL(resolve(process.argv[2])).href);
const { chromium } = await import(pathToFileURL(resolve(process.argv[3])).href);
const directory = await mkdtemp(join(tmpdir(), "champion-register-ui-"));
let browser;
let checks = 0;
const check = (condition, message) => { assert.ok(condition, message); checks++; };
try {
  const bundle = join(directory, "fixture.js");
  await build({ entryPoints: [join(root, "tests/ui/training-register-fixture.jsx")], outfile: bundle, bundle: true, platform: "browser", format: "iife", jsx: "automatic", tsconfig: join(root, "tsconfig.json"), define: { "process.env.NODE_ENV": '"test"' }, alias: { "next/image": join(root, "tests/ui/image-stub.jsx") } });
  const source = await readFile(bundle), styles = await readFile(join(root, "app/globals.css"));
  browser = await chromium.launch({ executablePath: resolve(process.argv[4]), headless: true, args: ["--no-sandbox", "--disable-dev-shm-usage"] });
  const errors = [];
  const page = await browser.newPage({ viewport: { width: 360, height: 800 } });
  page.on("pageerror", (error) => errors.push(error.message));
  await page.route("**/*", async (route) => {
    const url = new URL(route.request().url());
    if (url.origin !== "https://register-check.test") throw new Error(`Unexpected network request: ${url.origin}`);
    if (url.pathname === "/fixture.js") return route.fulfill({ body: source, contentType: "application/javascript" });
    if (url.pathname === "/style.css") return route.fulfill({ body: styles, contentType: "text/css" });
    return route.fulfill({ body: '<!doctype html><html lang="uk"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><link rel="stylesheet" href="/style.css"><div id="root"></div><script src="/fixture.js"></script></html>', contentType: "text/html" });
  });
  const save = () => page.getByRole("button", { name: "Зберегти присутність", exact: true }).click();
  const finishNoCards = () => page.getByRole("button", { name: "Карток немає — завершити облік", exact: true });
  const open = async () => { await page.evaluate(() => window.registerQa.open()); await page.getByText("Присутність і жовті картки", { exact: true }).waitFor(); };
  const reset = async () => { await page.evaluate(() => window.registerQa.reset()); await page.reload(); await page.getByText("Присутність і жовті картки", { exact: true }).waitFor(); };
  await page.goto("https://register-check.test");
  await page.getByText("Присутність і жовті картки", { exact: true }).waitFor();
  check(await finishNoCards().isDisabled(), "finalization requires saved attendance");
  check(await page.getByRole("button", { name: "Жовта картка", exact: true }).count() === 0, "new cards require saved presence");
  await page.getByRole("group", { name: "Присутність · Тестовий Гравець Б", exact: true }).getByRole("button", { name: "Відсутній", exact: true }).click();
  await save();
  await page.getByText(/Присутність збережено: 1 присутніх, 1 відсутніх/).waitFor();
  check(await finishNoCards().isEnabled(), "saving attendance alone does not finalize the register");
  check(await page.getByRole("button", { name: "Жовта картка", exact: true }).count() === 1, "only the present participant can receive a card");
  await page.evaluate(() => { window.registerQa.db.events[0].start_at = "2000-01-01T08:00:00Z"; });
  await open();
  check(await page.getByRole("button", { name: "Жовта картка", exact: true }).isEnabled(), "card entry is not limited by an old training date");
  await page.evaluate(() => { window.registerQa.mode = "card-pending"; });
  await page.getByRole("button", { name: "Жовта картка", exact: true }).click();
  await page.getByRole("button", { name: "Зафіксувати картку", exact: true }).click();
  check(await finishNoCards().isDisabled(), "cannot finalize while the card request is pending");
  await page.evaluate(() => { window.registerQa.mode = "normal"; window.registerQa.resolveCard(); });
  await page.getByText("Картку збережено", { exact: true }).waitFor();
  check(await page.getByText("Запізнення", { exact: true }).count() > 0, "saved card reason is visible");
  const cardCall = await page.evaluate(() => window.registerQa.calls.find((call) => call.table === "player_behavior_cards" && call.operation === "insert"));
  check(cardCall.payload.occurred_on === "2000-01-01", "card belongs to training date, not entry date");
  for (const width of [320, 360, 390, 768]) {
    await page.setViewportSize({ width, height: 900 });
    const layout = await page.locator(".modal-card").evaluate((modal) => ({ body: modal.querySelector(".modal-body").clientWidth, scroll: modal.querySelector(".modal-body").scrollWidth, footer: modal.querySelector("footer").getBoundingClientRect().right, viewport: innerWidth }));
    check(layout.scroll <= layout.body + 1 && layout.footer <= layout.viewport, `no horizontal overflow at ${width}px`);
  }
  if (process.env.CHAMPION_UI_SCREENSHOT_DIR) await page.screenshot({ path: join(resolve(process.env.CHAMPION_UI_SCREENSHOT_DIR), "training-register-mobile.png") });
  await page.evaluate(() => { window.registerQa.db.events[0].start_at = new Date().toISOString(); });
  await page.getByRole("button", { name: "Завершити облік тренування", exact: true }).click();
  await page.getByText("✓ Облік завершено · присутні 1 із 2 · жовтих карток 1", { exact: true }).first().waitFor();
  check(await page.evaluate(() => window.registerQa.db.events[0].status === "scheduled"), "finalization does not change event or booking status");
  await page.reload();
  await page.getByText("✓ Облік завершено · присутні 1 із 2 · жовтих карток 1", { exact: true }).first().waitFor();
  check(await page.locator(".training-register-badge.completed").count() > 0, "persisted summary remains on the calendar after reload");
  await open();
  check(await page.getByRole("button", { name: "Облік завершено", exact: true }).isDisabled(), "repeat opening does not unset completion");
  await page.getByRole("button", { name: "Анулювати помилкову", exact: true }).click();
  await page.getByLabel("Причина анулювання").fill("Тестова помилка");
  await page.getByRole("button", { name: "Підтвердити анулювання", exact: true }).click();
  await finishNoCards().waitFor();
  check(await finishNoCards().isEnabled(), "voiding invalidates completion and allows reconfirmation");
  check(await page.evaluate(() => window.registerQa.db.player_behavior_cards[0].is_voided && window.registerQa.db.player_behavior_cards[0].void_reason === "Тестова помилка"), "voiding keeps history");
  await page.evaluate(() => { window.registerQa.mode = "null-finalize"; });
  await finishNoCards().click();
  await page.getByText(/Облік не завершено\. Перевірте підключення/).waitFor();
  check(await finishNoCards().isEnabled(), "null success response never reports completion");
  await page.evaluate(() => { window.registerQa.mode = "stale-register"; });
  await finishNoCards().click();
  await page.getByText(/Відмітки змінилися в іншому вікні/).waitFor();
  check(await finishNoCards().isEnabled(), "concurrent changes require review instead of a false success");
  await reset();
  await page.evaluate(() => { Object.defineProperty(navigator, "onLine", { value: false, configurable: true }); window.dispatchEvent(new Event("offline")); });
  await save();
  await page.getByText(/Очікує синхронізації\. Присутність збережена на цьому пристрої/).waitFor();
  check(await finishNoCards().isDisabled(), "offline attendance cannot finalize the register");
  await page.reload();
  await page.getByText("Присутність і жовті картки", { exact: true }).waitFor();
  check(await finishNoCards().isDisabled(), "pending offline queue survives reload and blocks finalization");
  check(await page.getByText("Очікує синхронізації", { exact: true }).count() > 0, "pending state remains explicit after reload");
  await page.evaluate(() => window.registerQa.flush());
  await page.getByText(/Присутність синхронізовано/).waitFor();
  check(await finishNoCards().isEnabled(), "sync enables confirmation without silently completing it");
  await finishNoCards().click();
  await page.getByText("✓ Облік завершено · присутні 2 із 2 · жовтих карток 0", { exact: true }).first().waitFor();
  check(await page.evaluate(() => window.registerQa.db.training_register_completions[0].card_count === 0), "no-card completion requires one confirmation, no per-child checkbox");
  await reset();
  await page.evaluate(() => { window.registerQa.mode = "read-error"; window.registerQa.open(); });
  await page.getByRole("button", { name: "Повторити завантаження", exact: true }).waitFor();
  check(await page.getByRole("button", { name: "Зберегти присутність", exact: true }).isDisabled(), "partial load cannot overwrite attendance");
  check(await finishNoCards().isDisabled(), "partial load cannot finalize");
  check(errors.length === 0, `no uncaught runtime errors: ${errors.join("; ")}`);
  console.log(`PASS: ${checks} isolated browser checks; no staging/production requests or real accounts.`);
} finally { await browser?.close(); await rm(directory, { recursive: true, force: true }); }
